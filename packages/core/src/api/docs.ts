/**
 * Markdown API docs. Tables and examples come from the spec (deterministic);
 * only the short per-endpoint descriptions are written by the model.
 */
import { exampleFromSchema } from "./cases.js";
import { groupByTag, type ApiIndex, type Endpoint } from "./spec.js";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
const anchor = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

function exampleRequest(e: Endpoint, baseUrl: string): string {
  const path = e.path.replace(/\{([^}]+)\}/g, (_, name: string) => {
    const p = e.parameters.find((x) => x.in === "path" && x.name === name);
    return encodeURIComponent(String(exampleFromSchema(p?.schema) ?? name));
  });
  const query = e.parameters
    .filter((p) => p.in === "query" && p.required)
    .map(
      (p) =>
        `${encodeURIComponent(p.name)}=${encodeURIComponent(String(exampleFromSchema(p.schema)))}`,
    );
  const lines = [
    `${e.method.toUpperCase()} ${baseUrl}${path}${query.length ? `?${query.join("&")}` : ""}`,
  ];
  for (const p of e.parameters.filter((x) => x.in === "header" && x.required))
    lines.push(`${p.name}: ${String(exampleFromSchema(p.schema))}`);
  if (e.requestBody) {
    lines.push(
      `Content-Type: ${e.requestBody.contentType}`,
      "",
      JSON.stringify(exampleFromSchema(e.requestBody.schema), null, 2),
    );
  }
  return lines.join("\n");
}

function endpointSection(e: Endpoint, description: string | undefined, baseUrl: string): string {
  const out = [
    `### ${e.method.toUpperCase()} \`${e.path}\`${e.deprecated ? " (deprecated)" : ""}`,
    "",
  ];
  const text = description ?? e.summary ?? e.description;
  if (text) out.push(text, "");
  if (e.security.length)
    out.push(`**Auth:** ${e.security.map((s) => s.join(" + ")).join(" or ")}`, "");
  if (e.parameters.length) {
    out.push(
      "| Parameter | In | Type | Required | Description |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const p of e.parameters)
      out.push(
        `| \`${esc(p.name)}\` | ${p.in} | ${esc(p.type)} | ${p.required ? "yes" : "no"} | ${esc(p.description ?? "")} |`,
      );
    out.push("");
  }
  if (e.requestBody) {
    const props = (e.requestBody.schema.properties ?? {}) as Record<
      string,
      Record<string, unknown>
    >;
    const required = new Set((e.requestBody.schema.required as string[]) ?? []);
    out.push(
      `**Request body** (${e.requestBody.contentType}${e.requestBody.required ? ", required" : ""})`,
      "",
    );
    if (Object.keys(props).length) {
      out.push("| Field | Type | Required | Description |", "| --- | --- | --- | --- |");
      for (const [name, s] of Object.entries(props)) {
        const t = Array.isArray(s.type)
          ? s.type.join(" | ")
          : String(s.type ?? (s.properties ? "object" : "any"));
        out.push(
          `| \`${esc(name)}\` | ${esc(s.enum ? `${t} (${(s.enum as unknown[]).map(String).join(", ")})` : t)} | ${required.has(name) ? "yes" : "no"} | ${esc(String(s.description ?? ""))} |`,
        );
      }
      out.push("");
    }
  }
  out.push("| Status | Description |", "| --- | --- |");
  for (const r of e.responses) out.push(`| ${r.status} | ${esc(r.description ?? "")} |`);
  out.push("", "**Example request**", "", "```http", exampleRequest(e, baseUrl), "```", "");
  const ok =
    e.responses.find((r) => /^2/.test(r.status) && r.schema) ?? e.responses.find((r) => r.schema);
  if (ok?.schema)
    out.push(
      `**Example response** (${ok.status})`,
      "",
      "```json",
      JSON.stringify(exampleFromSchema(ok.schema), null, 2),
      "```",
      "",
    );
  return out.join("\n");
}

/** Renders the whole API as Markdown, grouped by tag. */
export function renderDocs(index: ApiIndex, descriptions: Map<string, string> = new Map()): string {
  const baseUrl = (index.servers[0] ?? "https://api.example.com").replace(/\/+$/, "");
  const groups = groupByTag(index);
  const out = [
    `# ${index.title}${index.version ? ` ${index.version}` : ""}`,
    "",
    `Base URL: \`${baseUrl}\``,
    "",
  ];
  if (Object.keys(index.securitySchemes).length) {
    out.push("## Authentication", "");
    for (const [name, detail] of Object.entries(index.securitySchemes))
      out.push(`- **${name}**: ${detail}`);
    out.push("");
  }
  out.push("## Contents", "");
  for (const [tag, endpoints] of groups) {
    out.push(`- [${tag}](#${anchor(tag)})`);
    for (const e of endpoints) out.push(`  - ${e.method.toUpperCase()} \`${e.path}\``);
  }
  out.push("");
  for (const [tag, endpoints] of groups) {
    out.push(`## ${tag}`, "");
    for (const e of endpoints) out.push(endpointSection(e, descriptions.get(e.key), baseUrl));
  }
  out.push(
    "---",
    "",
    "_Generated by Mofu APIForge. Tables and examples come from the spec; descriptions were written by AI._",
    "",
  );
  return out.join("\n");
}
