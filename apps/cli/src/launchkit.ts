// ---------------------------------------------------------------- the command

export async function runLaunchKit(args: LaunchKitArgs, printer: Printer): Promise<number> {
  try {
    const files = kitFiles(args);
    const dir = path.resolve(args.dir ?? args.symbol.trim().toLowerCase());
    const existing = await readdir(dir).catch(() => null);
    if (existing && existing.length > 0) {
      printer.error(`${dir} isn't empty. Pick a new folder.`);
      return 1;
    }
    for (const [rel, text] of Object.entries(files)) {
      await mkdir(path.dirname(path.join(dir, rel)), { recursive: true });
      await writeFile(path.join(dir, rel), text);
    }
    printer.line(pc.green(`Created ${dir}`));
    for (const rel of Object.keys(files)) printer.line(pc.dim(`  ${rel}`));
    const audit = await auditPath("src", dir);
    const f = audit.files[0];
    if (f) {
      const flagged = f.checks.filter((c) => c.status === "risk" || c.status === "warn").length;
      printer.line("");
      printer.line(
        `mofu audit: the Token Scanner would likely say ${f.verdict === "clean" ? pc.green(pc.bold("CLEAN")) : pc.yellow(f.verdict.toUpperCase())}` +
          pc.dim(
            ` (${flagged} flagged checks, ${f.issues.filter((i) => i.severity !== "info").length} code issues)`,
          ),
      );
    }
    printer.line("");
    printer.line("Next:");
    printer.line(`  cd ${path.relative(process.cwd(), dir) || "."}`);
    printer.line("  forge test                         # needs Foundry: https://getfoundry.sh");
    printer.line("  cast wallet import deployer --interactive");
    const sol = Object.keys(files).find((k) => k.startsWith("src/"))!;
    const contract = path.basename(sol, ".sol");
    printer.line(
      `  forge create ${sol}:${contract} --rpc-url robinhood --account deployer --broadcast`,
    );
    printer.line(
      pc.dim(
        "Mofu never sees your key: it's in Foundry's encrypted keystore. Details in README.md.",
      ),
    );
    return 0;
  } catch (err) {
    printer.error(err instanceof Error ? err.message : String(err));
    return 1;
  }
}
